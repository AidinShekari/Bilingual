#!/usr/bin/env python3
"""Regenerate the data-driven PGFPlots figures (coordinates computed here,
so every curve in the notes is reproducible).  Usage:  python3 scripts/make_plot_data.py
"""
import os
from acnmath import erlang_b

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def write(rel, text):
    path = os.path.join(ROOT, "figures", rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote", rel)

def coords(pairs, fmt="({:.4g},{:.4g})"):
    return " ".join(fmt.format(x, y) for x, y in pairs)

def erlang_plot():
    series = []
    for m in (8, 30, 94):
        pts = []
        A = 0.25
        while A <= 100:
            b = erlang_b(A, m)
            if b >= 1e-4:
                pts.append((A, b))
            A += 0.25 if A < 10 else 1.0
        series.append((m, pts))
    body = "\n".join(
        "  \\addplot+[no marks] coordinates {%s};" % coords(p) for _, p in series)
    legend = ",".join("$m=%d$" % m for m, _ in series)
    write("lecture-02/erlang-b.tex", r"""% Erlang-B blocking probability vs offered traffic (generated by scripts/make_plot_data.py)
\begin{tikzpicture}
\begin{axis}[acnplot,width=0.8\linewidth,height=6cm,ymode=log,
  xlabel={\bil{offered traffic $A$ [E]}{ترافیک ارائه‌شده $A$ [E]}},
  ylabel={\bil{blocking probability $P_{\mathrm{B}}$}{احتمال انسداد $P_{\mathrm{B}}$}},
  xmin=0,xmax=100,ymin=1e-4,ymax=1,legend pos=south east]
@BODY@
  \addplot+[no marks,domain=0:100,samples=2,acngray,densely dashed] {0.02};
  \legend{@LEGEND@,$P_{\mathrm{B}}=2\%$}
\end{axis}
\end{tikzpicture}
""".replace("@BODY@", body).replace("@LEGEND@", legend))

def scheduler_plot():
    from scheduler_sim import results, MEAN_SNR_DB
    res = results()
    body = []
    for pol in ("RR", "PF", "MaxCI"):
        thr = res[pol][0]
        body.append("  \\addplot coordinates {%s};" % " ".join(
            "(u%d,%.2f)" % (k + 1, v) for k, v in enumerate(thr)))
    labels = ",".join("{UE%d\\\\[-2pt]%g dB}" % (k + 1, m) for k, m in enumerate(MEAN_SNR_DB))
    write("lecture-07/scheduler-results.tex", r"""% per-user throughput for RR/PF/MaxCI (generated by scripts/make_plot_data.py)
\begin{tikzpicture}
\begin{axis}[acnplot,ybar,bar width=9pt,width=0.86\linewidth,height=5.8cm,
  symbolic x coords={u1,u2,u3,u4},xtick=data,xticklabels={@LABELS@},
  x tick label style={align=center,font=\scriptsize},enlarge x limits=0.18,
  ylabel={\bil{throughput [Mbit/s]}{گذردهی [Mbit/s]}},ymin=0,ymax=40,
  legend style={at={(0.98,0.97)},anchor=north east},
  cycle list={{fill=acnblue!45,draw=acnblue},{fill=acnteal!60,draw=acnteal},{fill=acnamber!55,draw=acnamber}}]
@BODY@
  \legend{RR,PF,Max C/I}
\end{axis}
\end{tikzpicture}
""".replace("@BODY@", "\n".join(body)).replace("@LABELS@", labels))

PLOTS = [erlang_plot, scheduler_plot]

if __name__ == "__main__":
    for p in PLOTS:
        p()
